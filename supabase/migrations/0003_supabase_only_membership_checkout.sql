create table if not exists public.membership_plans (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  description text not null default '',
  price_idr bigint not null check (price_idr >= 0),
  duration_days integer not null check (duration_days > 0),
  benefits jsonb not null default '[]'::jsonb,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);
create table if not exists public.user_memberships (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  plan_id bigint not null references public.membership_plans(id) on delete restrict,
  status text not null default 'active' check (status in ('active','expired','cancelled')),
  starts_at timestamptz not null default now(),
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);
create table if not exists public.membership_transactions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  plan_id bigint not null references public.membership_plans(id),
  amount_idr bigint not null check (amount_idr >= 0),
  payment_method text not null default 'simulation',
  status text not null check (status in ('paid','failed')),
  created_at timestamptz not null default now()
);
alter table public.membership_plans enable row level security;
alter table public.user_memberships enable row level security;
alter table public.membership_transactions enable row level security;
drop policy if exists products_read_published on public.products;
create or replace function public.has_active_membership(p_user_id uuid default auth.uid())
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.user_memberships m
    where m.user_id = p_user_id and m.status = 'active'
      and m.starts_at <= now() and m.expires_at > now()
  );
$$;
create policy membership_plans_read on public.membership_plans
for select to anon, authenticated using (is_active = true);
create policy memberships_read_own on public.user_memberships
for select to authenticated using (user_id = (select auth.uid()));
create policy membership_transactions_read_own on public.membership_transactions
for select to authenticated using (user_id = (select auth.uid()));
create policy products_read_published on public.products
for select to anon, authenticated using (
  is_published = true and exists (
    select 1 from public.categories c
    where c.id = category_id and c.is_active = true
      and (c.slug <> 'collectible' or public.has_active_membership((select auth.uid())))
  )
);
grant select on public.membership_plans to anon, authenticated;
grant select on public.user_memberships, public.membership_transactions to authenticated;
grant execute on function public.has_active_membership(uuid) to anon, authenticated;

