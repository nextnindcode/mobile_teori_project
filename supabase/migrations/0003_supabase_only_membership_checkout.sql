create or replace function public.purchase_membership_simulated(p_plan_id bigint)
returns jsonb language plpgsql security definer set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_plan public.membership_plans%rowtype;
  v_expires timestamptz;
  v_tx uuid;
  v_membership uuid;
begin
  if v_uid is null then raise exception 'Authentication required'; end if;
  if public.has_active_membership(v_uid) then raise exception 'Membership is already active'; end if;
  select * into v_plan from public.membership_plans
    where id = p_plan_id and is_active = true for update;
  if not found then raise exception 'Membership plan unavailable'; end if;
  v_expires := now() + make_interval(days => v_plan.duration_days);
  insert into public.membership_transactions(user_id,plan_id,amount_idr,payment_method,status)
    values(v_uid,v_plan.id,v_plan.price_idr,'simulation','paid') returning id into v_tx;
  insert into public.user_memberships(user_id,plan_id,status,starts_at,expires_at)
    values(v_uid,v_plan.id,'active',now(),v_expires) returning id into v_membership;
  insert into public.notifications(user_id,title,message,type)
    values(v_uid,'Membership aktif','Membership “'||v_plan.name||'” aktif sampai '||v_expires::date,'system');
  return jsonb_build_object('transaction_id',v_tx,'membership_id',v_membership,'expires_at',v_expires,'status','paid');
end;
$$;
grant execute on function public.purchase_membership_simulated(bigint) to authenticated;

create or replace function public.checkout_merchandise(p_items jsonb)
returns jsonb language plpgsql security definer set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_item jsonb;
  v_product public.products%rowtype;
  v_category text;
  v_qty integer;
  v_total bigint := 0;
  v_order uuid;
  v_item_count integer := 0;
begin
  if v_uid is null then raise exception 'Authentication required'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Keranjang kosong';
  end if;
  for v_item in select value from jsonb_array_elements(p_items) loop
    v_qty := (v_item->>'quantity')::integer;
    if v_qty <= 0 then raise exception 'Jumlah produk tidak valid'; end if;
    select p.* into v_product from public.products p
      where p.id = (v_item->>'product_id')::bigint and p.is_published = true for update;
    if not found then raise exception 'Produk tidak tersedia'; end if;
    select c.slug into v_category from public.categories c where c.id = v_product.category_id and c.is_active = true;
    if v_category = 'collectible' and not public.has_active_membership(v_uid) then
      raise exception 'Collectibles hanya tersedia untuk member aktif';
    end if;
    if v_product.stock < v_qty then raise exception 'Stok produk tidak mencukupi'; end if;
    v_total := v_total + v_product.price_idr * v_qty;
  end loop;
  insert into public.orders(user_id,total_idr,status) values(v_uid,v_total,'confirmed') returning id into v_order;
  for v_item in select value from jsonb_array_elements(p_items) loop
    v_qty := (v_item->>'quantity')::integer;
    select p.* into v_product from public.products p where p.id = (v_item->>'product_id')::bigint for update;
    update public.products set stock = stock - v_qty, updated_at = now() where id = v_product.id;
    insert into public.order_items(order_id,product_id,product_name_snapshot,quantity,unit_price_idr)
      values(v_order,v_product.id,v_product.name,v_qty,v_product.price_idr);
  end loop;
  insert into public.notifications(user_id,title,message,type)
    values(v_uid,'Checkout berhasil','Pesanan '||v_order::text||' berhasil dibuat. Pembayaran merchandise bersifat simulasi.','order');
  return jsonb_build_object('order_id',v_order,'total_idr',v_total,'status','confirmed','payment_method','simulation');
end;
$$;
grant execute on function public.checkout_merchandise(jsonb) to authenticated;

