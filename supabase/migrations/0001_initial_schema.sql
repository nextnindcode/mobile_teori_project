-- ---------------------------------------------------------------------------
-- SAFE QUIZ SUBMISSION: server calculates score and awards points.
-- p_answers must be an array of objects: [{"question_id": 1, "answer": "A"}, ...]
-- The client cannot set its own score or point reward.
-- ---------------------------------------------------------------------------
create or replace function public.submit_quiz_attempt(p_answers jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_item jsonb;
  v_question public.quiz_questions%rowtype;
  v_count integer := 0;
  v_correct integer := 0;
  v_score integer := 0;
  v_points integer := 0;
  v_score_id uuid;
begin
  if v_uid is null then
    raise exception 'Authentication required';
  end if;
  if jsonb_typeof(p_answers) <> 'array'
     or jsonb_array_length(p_answers) < 1
     or jsonb_array_length(p_answers) > 10 then
    raise exception 'Submit between 1 and 10 answers';
  end if;

  for v_item in select value from jsonb_array_elements(p_answers)
  loop
    if not (v_item ? 'question_id') or not (v_item ? 'answer') then
      raise exception 'Each answer needs question_id and answer';
    end if;
    select * into v_question
    from public.quiz_questions
    where id = (v_item ->> 'question_id')::bigint and is_active = true;
    if not found then
      raise exception 'Question not found or inactive';
    end if;
    v_count := v_count + 1;
    if v_item ->> 'answer' = v_question.correct_option then
      v_correct := v_correct + 1;
      v_points := v_points + v_question.points;
    end if;
  end loop;

  if (select count(distinct (value ->> 'question_id'))
      from jsonb_array_elements(p_answers)) <> v_count then
    raise exception 'Duplicate question IDs are not allowed';
  end if;

  v_score := v_points;
  insert into public.game_scores(user_id, score, correct_count, question_count)
  values (v_uid, v_score, v_correct, v_count)
  returning id into v_score_id;

  insert into public.user_points(user_id, total_points, updated_at)
  values (v_uid, v_points, now())
  on conflict (user_id) do update
    set total_points = public.user_points.total_points + excluded.total_points,
        updated_at = now();

  if v_points > 0 then
    insert into public.point_transactions(user_id, amount, transaction_type, reference_id, description)
    values (v_uid, v_points, 'quiz_reward', v_score_id, 'Reward from quiz attempt');
  end if;

  return jsonb_build_object(
    'attempt_id', v_score_id,
    'score', v_score,
    'correct_count', v_correct,
    'question_count', v_count,
    'points_earned', v_points
  );
end;
$$;

-- ---------------------------------------------------------------------------
-- SAFE PHOTOCARD REDEMPTION: point deduction + ownership + history are atomic.
-- Shake/tap animation belongs in Flutter; it must not itself award a card.
-- ---------------------------------------------------------------------------
create or replace function public.redeem_photocard(p_card_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_cost integer;
  v_redemption_id uuid;
begin
  if v_uid is null then
    raise exception 'Authentication required';
  end if;

  select points_cost into v_cost
  from public.cards
  where id = p_card_id and is_available = true
  for update;
  if not found then
    raise exception 'Photocard is unavailable';
  end if;

  insert into public.user_points(user_id, total_points)
  values (v_uid, 0)
  on conflict (user_id) do nothing;

  update public.user_points
  set total_points = total_points - v_cost, updated_at = now()
  where user_id = v_uid and total_points >= v_cost;
  if not found then
    raise exception 'Not enough points';
  end if;

  insert into public.user_cards(user_id, card_id, acquisition_source)
  values (v_uid, p_card_id, 'redemption');

  insert into public.redemption_transactions(user_id, card_id, points_spent)
  values (v_uid, p_card_id, v_cost)
  returning id into v_redemption_id;

  insert into public.point_transactions(user_id, amount, transaction_type, reference_id, description)
  values (v_uid, -v_cost, 'photocard_redemption', v_redemption_id, 'Photocard redemption');

  return jsonb_build_object(
    'redemption_id', v_redemption_id,
    'card_id', p_card_id,
    'points_spent', v_cost
  );
end;
$$;

