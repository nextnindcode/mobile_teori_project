-- EclipseVerse Supabase initial schema
-- Fresh database only. This does NOT migrate old MySQL data.
-- Run in Supabase SQL Editor on a NEW project.
-- Sensitive mutations (orders, stock, points, card redemption, blockchain ledger)
-- are intentionally not exposed to direct client writes yet; add secure RPC/Edge Functions first.

create extension if not exists pgcrypto;

-- Auth users are managed by Supabase Auth. This table stores app-facing profile data.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null default '',
  email text not null default '',
  role text not null default 'user' check (role in ('admin', 'user')),
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, name, email, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'name', ''),
    coalesce(new.email, ''),
    'user'
  )
  on conflict (id) do update
    set name = excluded.name, email = excluded.email;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null check (category in ('album', 'apparel', 'accessory', 'collectible')),
  description text,
  image_url text,
  price integer not null check (price >= 0),
  stock integer not null default 0 check (stock >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.members (
  id bigint generated by default as identity primary key,
  stage_name text not null,
  position text not null,
  description text,
  fun_fact text not null
);

create table if not exists public.events (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  event_date timestamptz not null,
  venue text,
  city text,
  latitude numeric(9,6),
  longitude numeric(9,6)
);

create table if not exists public.currency_rates (
  id bigint generated by default as identity primary key,
  base_code char(3) not null,
  target_code char(3) not null,
  rate numeric(18,6) not null check (rate > 0),
  updated_at timestamptz not null default now(),
  unique (base_code, target_code)
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete restrict,
  total integer not null check (total >= 0),
  status text not null default 'CONFIRMED'
    check (status in ('PENDING', 'CONFIRMED', 'PAID', 'CANCELLED', 'COMPLETED')),
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete restrict,
  quantity integer not null check (quantity > 0),
  unit_price integer not null check (unit_price >= 0)
);

create table if not exists public.feedback (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete restrict,
  rating integer not null check (rating between 1 and 5),
  impression text not null check (char_length(impression) between 1 and 500),
  suggestion text not null check (char_length(suggestion) between 1 and 500),
  created_at timestamptz not null default now()
);

create table if not exists public.game_scores (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete restrict,
  score integer not null check (score between 0 and 100),
  correct_count integer not null check (correct_count between 0 and 10),
  played_at timestamptz not null default now(),
  check (score = correct_count * 10)
);

create table if not exists public.user_points (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  total_points integer not null default 0 check (total_points >= 0)
);

create table if not exists public.user_cards (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  card_id integer not null check (card_id between 1 and 13),
  redeemed_at timestamptz not null default now(),
  unique (user_id, card_id)
);

create table if not exists public.notifications (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  title text not null,
  message text not null,
  type text not null check (type in ('order', 'system')),
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.blockchain_ledger (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete set null,
  action_type text not null,
  transaction_data jsonb not null,
  previous_hash char(64) not null,
  current_hash char(64) not null unique,
  created_at timestamptz not null default now()
);

create index if not exists idx_orders_user_created on public.orders (user_id, created_at desc);
create index if not exists idx_order_items_order on public.order_items (order_id);
create index if not exists idx_feedback_created on public.feedback (created_at desc);
create index if not exists idx_game_scores_user_played on public.game_scores (user_id, played_at desc);
create index if not exists idx_notifications_user_created on public.notifications (user_id, created_at desc);
create index if not exists idx_ledger_user_created on public.blockchain_ledger (user_id, created_at desc);

