-- Profiles: a signed-in user can read only their own profile.
drop policy if exists "profiles_select_own" on public.profiles;
create policy "profiles_select_own" on public.profiles
for select to authenticated using (id = (select auth.uid()));

-- Public catalogue/reference data is readable by app users, including logged-out users.
drop policy if exists "products_read" on public.products;
create policy "products_read" on public.products
for select to anon, authenticated using (true);
drop policy if exists "members_read" on public.members;
create policy "members_read" on public.members
for select to anon, authenticated using (true);
drop policy if exists "events_read" on public.events;
create policy "events_read" on public.events
for select to anon, authenticated using (true);
drop policy if exists "currency_rates_read" on public.currency_rates;
create policy "currency_rates_read" on public.currency_rates
for select to anon, authenticated using (true);

-- Feedback: authenticated users may read reviews and insert only under their own user ID.
drop policy if exists "feedback_read_authenticated" on public.feedback;
create policy "feedback_read_authenticated" on public.feedback
for select to authenticated using (true);
drop policy if exists "feedback_insert_own" on public.feedback;
create policy "feedback_insert_own" on public.feedback
for insert to authenticated
with check (user_id = (select auth.uid()));

-- Users can read their own orders and order items only. Mutations are server-only for now.
drop policy if exists "orders_read_own" on public.orders;
create policy "orders_read_own" on public.orders
for select to authenticated using (user_id = (select auth.uid()));
drop policy if exists "order_items_read_own" on public.order_items;
create policy "order_items_read_own" on public.order_items
for select to authenticated using (
  exists (
    select 1 from public.orders o
    where o.id = order_items.order_id and o.user_id = (select auth.uid())
  )
);

-- User-scoped private data. No client writes for points/cards/scores/ledger until secure functions exist.
drop policy if exists "notifications_read_own" on public.notifications;
create policy "notifications_read_own" on public.notifications
for select to authenticated using (user_id = (select auth.uid()));
drop policy if exists "notifications_update_own" on public.notifications;
create policy "notifications_update_own" on public.notifications
for update to authenticated using (user_id = (select auth.uid()))
with check (user_id = (select auth.uid()));

drop policy if exists "scores_read_own" on public.game_scores;
create policy "scores_read_own" on public.game_scores
for select to authenticated using (user_id = (select auth.uid()));
drop policy if exists "points_read_own" on public.user_points;
create policy "points_read_own" on public.user_points
for select to authenticated using (user_id = (select auth.uid()));
drop policy if exists "cards_read_own" on public.user_cards;
create policy "cards_read_own" on public.user_cards
for select to authenticated using (user_id = (select auth.uid()));
drop policy if exists "ledger_read_own" on public.blockchain_ledger;
create policy "ledger_read_own" on public.blockchain_ledger
for select to authenticated using (user_id = (select auth.uid()));

